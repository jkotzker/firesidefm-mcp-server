// Compares the Fireside API documentation, API version probes and blog with the committed baseline.
// Run daily by .github/workflows/upstream-watch.yml; it needs no API key and sends no authenticated requests.
//
//   npx tsx scripts/upstream-watch.ts                     # print what changed; exit 0 either way
//   npx tsx scripts/upstream-watch.ts --report out.md     # also write an issue body when something changed
//   npx tsx scripts/upstream-watch.ts --update            # replace the baseline with the current state
//
// Under GitHub Actions it also sets the step output `changed` to true or false.

import { appendFileSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

import {
  BLOG_RSS_URL,
  DOCS_URL,
  PROBES,
  blogFingerprint,
  diffFingerprints,
  docsFingerprint,
  hasChanges,
  report,
} from './upstream-fingerprint.js';

const BASELINE_PATH = 'scripts/fireside-api-baseline.txt';
const BASELINE_FILE = fileURLToPath(new URL('fireside-api-baseline.txt', import.meta.url));
const HEADER = `# Generated by scripts/upstream-watch.ts --update from ${DOCS_URL}, the API version probes and ${BLOG_RSS_URL}. Do not edit by hand.`;
const TIMEOUT_MS = 30_000;
const HEADERS = { 'User-Agent': 'firesidefm-mcp-server upstream-watch (+https://github.com/jkotzker/firesidefm-mcp-server)' };

async function text(url: string): Promise<string> {
  const response = await fetch(url, { headers: HEADERS, signal: AbortSignal.timeout(TIMEOUT_MS) });
  if (!response.ok) throw new Error(`GET ${url} returned ${response.status}.`);
  return response.text();
}

async function probe(spec: string): Promise<string> {
  const [method = 'GET', path = '/'] = spec.split(' ');
  const response = await fetch(new URL(path, 'https://fireside.fm'), {
    method,
    headers: HEADERS,
    redirect: 'manual',
    signal: AbortSignal.timeout(TIMEOUT_MS),
  });
  await response.body?.cancel();
  return `probe ${spec} ${response.status}`;
}

async function current(): Promise<string[]> {
  const [docs, rss, ...probes] = await Promise.all([text(DOCS_URL), text(BLOG_RSS_URL), ...PROBES.map(probe)]);
  return [...docsFingerprint(docs), ...probes, ...blogFingerprint(rss)];
}

function readBaseline(): string[] {
  return readFileSync(BASELINE_FILE, 'utf8')
    .split('\n')
    .filter((line) => line !== '' && !line.startsWith('#'));
}

async function main(): Promise<void> {
  const { values } = parseArgs({ options: { update: { type: 'boolean' }, report: { type: 'string' } } });
  const now = await current();

  if (values.update) {
    writeFileSync(BASELINE_FILE, `${HEADER}\n${now.join('\n')}\n`);
    console.log(`Wrote ${now.length} lines to ${BASELINE_PATH}.`);
    return;
  }

  const diff = diffFingerprints(readBaseline(), now);
  const changed = hasChanges(diff);
  if (process.env['GITHUB_OUTPUT']) appendFileSync(process.env['GITHUB_OUTPUT'], `changed=${changed}\n`);
  if (!changed) {
    console.log('No change since the baseline.');
    return;
  }
  const body = report(diff, now, BASELINE_PATH);
  console.log(body);
  if (values.report) writeFileSync(values.report, body);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
